"""Benchmark an OpenAI-compatible vision model on labeled jersey crops.

The runner is intentionally resumable because large local VLMs are expensive to
load and individual requests may fail. It compares the existing tight crop with
the padded, red-box context generated by ``label_jersey_numbers.py``.
"""
from __future__ import annotations

import argparse
import base64
from datetime import datetime, timezone
import json
import mimetypes
from pathlib import Path
import re
import time
from urllib.error import HTTPError, URLError
from urllib.request import Request, urlopen

from scripts.build_jersey_audit_set import HEIGHT_BAND_ORDER, height_band_label
from scripts.label_jersey_numbers import score_model, write_json_atomic


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_DATASET = ROOT / "runs/ocr_labels/FelixClaar/dataset.json"
DEFAULT_MODEL = "qwen38-flash-next"
DEFAULT_BASE_URL = "http://127.0.0.1:8088/v1"

CONTEXT_PROMPT = (
    "The red rectangle marks a detected jersey-number region. Use the "
    "surrounding jersey context, but read only the complete number inside "
    "the rectangle. Return exactly one or two ASCII digits, or exactly "
    "NONE if it is unreadable, partial, occluded, or uncertain. Return "
    "nothing else."
)

VARIANTS = {
    "tight": {
        "path_key": "crop_path",
        "prompt": (
            "This image is a tight crop of a detected jersey-number region. "
            "Return the complete jersey number as exactly one or two ASCII "
            "digits. Return exactly NONE if the complete number is unreadable, "
            "partial, occluded, or uncertain. Return nothing else."
        ),
    },
    "context": {
        "path_key": "context_path",
        "prompt": CONTEXT_PROMPT,
    },
    # Same image as "context", read digit-by-digit instead of as a whole number.
    # The point is not just accuracy: whole-number mode answers a truncated "17" as
    # a confident "7", which the voter then counts as a wrong vote. Per-position
    # reading lets an unreadable digit come back as "?", which is evidence the voter
    # can fold rather than a wrong answer it has to survive.
    "context_digits": {
        "path_key": "context_path",
        "prompt": (
            "The red rectangle marks a detected jersey number. Read it one digit "
            "at a time, left to right. Return the digits separated by single "
            "spaces, using ? for any digit position you cannot read confidently. "
            "A jersey number has one or two digits. Examples: '2 5' for 25, "
            "'7' for 7, '? 3' when only the second digit is legible. Return "
            "exactly NONE if you cannot read any digit at all. Return nothing else."
        ),
        "parse": "digits",
    },
    # Identical image and prompt to "context", with the model's reasoning turned off.
    # Measured on the 1080p set, thinking-enabled reading answers 96% of crops and
    # abstains on only 44% of the ones a human called unreadable -- a reasoning model
    # talks itself into an answer. This arm isolates that: same everything, no
    # reasoning, ~10x cheaper per request.
    "context_nothink": {
        "path_key": "context_path",
        "prompt": CONTEXT_PROMPT,   # byte-identical to "context" -- only thinking differs
        "extra_body": {"chat_template_kwargs": {"enable_thinking": False}},
    },
}


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def parse_prediction(content: str) -> tuple[str, str]:
    """Return a normalized digit prediction and how it was parsed."""
    text = str(content or "").strip()
    text = re.sub(r"^```(?:json|text)?\s*|\s*```$", "", text, flags=re.I).strip()
    if re.fullmatch(r"[0-9]{1,2}", text):
        return text, "exact"
    if re.fullmatch(r"(?:none|unreadable|uncertain)", text, flags=re.I):
        return "", "abstain"
    try:
        payload = json.loads(text)
    except json.JSONDecodeError:
        payload = None
    if isinstance(payload, dict):
        value = payload.get("number", payload.get("value"))
        status = str(payload.get("status", "")).lower()
        if value is not None and re.fullmatch(r"[0-9]{1,2}", str(value).strip()):
            return str(value).strip(), "json"
        if status in {"unreadable", "uncertain", "none"}:
            return "", "json_abstain"
    numbers = re.findall(r"(?<![0-9])[0-9]{1,2}(?![0-9])", text)
    if len(numbers) == 1:
        return numbers[0], "single_number_fallback"
    if re.search(r"\b(?:none|unreadable|uncertain)\b", text, flags=re.I):
        return "", "abstain_fallback"
    return "", "malformed"


def parse_digit_sequence(content: str) -> tuple[str, str]:
    """Parse a per-digit reading like ``2 5`` / ``? 3`` into a number or abstention.

    A reading containing ``?`` is a *partial*: some position was legible and some
    was not. For number-level scoring that is an abstention -- we do not know the
    whole number -- but it is materially different from a blind guess, so the status
    records it and the raw tokens stay in the report for the partial-read analysis.
    """
    text = str(content or "").strip()
    text = re.sub(r"^```(?:json|text)?\s*|\s*```$", "", text, flags=re.I).strip()
    if re.fullmatch(r"(?:none|unreadable|uncertain)", text, flags=re.I):
        return "", "abstain"

    tokens = re.findall(r"[0-9?]", text)
    if not tokens or len(tokens) > 2:
        # Fall back to the whole-number parser so a model that ignored the format
        # instruction is still scored on what it actually said, not counted as junk.
        prediction, status = parse_prediction(content)
        return prediction, f"fallback_{status}"
    if "?" in tokens:
        return "", "partial_" + "".join(tokens)
    number = "".join(tokens)
    if number.startswith("0"):
        return "", "leading_zero"
    return number, "exact"


PARSERS = {"digits": parse_digit_sequence}


def parse_for_variant(variant: dict, content: str) -> tuple[str, str]:
    return PARSERS.get(variant.get("parse"), parse_prediction)(content)


def image_data_url(path: Path) -> str:
    mime_type = mimetypes.guess_type(path.name)[0] or "image/jpeg"
    encoded = base64.b64encode(path.read_bytes()).decode("ascii")
    return f"data:{mime_type};base64,{encoded}"


def extract_content(response: dict) -> str:
    content = response["choices"][0]["message"]["content"]
    if isinstance(content, str):
        return content
    if isinstance(content, list):
        return "".join(
            str(item.get("text", ""))
            for item in content
            if isinstance(item, dict) and item.get("type") == "text"
        )
    raise ValueError("response message has no text content")


def request_prediction(
    base_url: str,
    model: str,
    image_path: Path,
    prompt: str,
    timeout: float,
    max_tokens: int,
    extra_body: dict | None = None,
) -> tuple[str, dict]:
    payload = {
        "model": model,
        "messages": [{
            "role": "user",
            "content": [
                {"type": "text", "text": prompt},
                {
                    "type": "image_url",
                    "image_url": {"url": image_data_url(image_path)},
                },
            ],
        }],
        "temperature": 0,
        "max_tokens": max_tokens,
    }
    if extra_body:
        payload.update(extra_body)
    request = Request(
        f"{base_url.rstrip('/')}/chat/completions",
        data=json.dumps(payload).encode("utf-8"),
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    try:
        with urlopen(request, timeout=timeout) as response:
            body = json.load(response)
    except HTTPError as error:
        detail = error.read().decode("utf-8", errors="replace")
        raise RuntimeError(f"model server returned HTTP {error.code}: {detail}") from error
    except URLError as error:
        raise RuntimeError(f"could not reach model server: {error.reason}") from error
    return extract_content(body), body.get("usage", {})


def load_ground_truth(labels_path: Path) -> tuple[dict[int, str], set[int], int]:
    labels = json.loads(labels_path.read_text()).get("labels", {})
    readable = {
        int(index): str(item["value"])
        for index, item in labels.items()
        if item.get("status") == "readable"
    }
    unreadable = {
        int(index)
        for index, item in labels.items()
        if item.get("status") == "unreadable"
    }
    unsure = sum(item.get("status") == "unsure" for item in labels.values())
    if not readable:
        raise ValueError("no readable ground-truth labels found")
    return readable, unreadable, unsure


def summarize_variant(
    readable: dict[int, str], unreadable: set[int], raw: dict[str, dict]
) -> dict:
    """Score one variant's requests against ground truth.

    Takes `readable`/`unreadable` restricted to whatever index subset is being scored
    (the full eligible set, or one height band of it) so this is reusable for both the
    aggregate and the per-band breakdown without re-running requests.
    """
    eligible = sorted(set(readable) | unreadable)
    predictions = {
        index: raw[str(index)].get("prediction", "")
        for index in eligible
        if str(index) in raw
    }
    metrics = score_model(readable, predictions, unreadable)
    unreadable_predictions = len(unreadable) - metrics["unreadable_abstentions"]
    accepted_predictions = metrics["predicted_crops"] + unreadable_predictions
    overall_correct = metrics["correct"] + metrics["unreadable_abstentions"]
    metrics.update({
        "accepted_predictions": accepted_predictions,
        "accepted_precision": (
            metrics["correct"] / accepted_predictions if accepted_predictions else None
        ),
        "overall_correct": overall_correct,
        "overall_decision_accuracy": overall_correct / len(eligible) if eligible else None,
    })
    metrics["malformed_responses"] = sum(
        raw[str(index)].get("parse_status") == "malformed"
        for index in eligible
        if str(index) in raw
    )
    metrics["completed_requests"] = sum(str(index) in raw for index in eligible)
    return metrics


def stratify_by_height(
    readable: dict[int, str],
    unreadable: set[int],
    samples: dict[int, dict],
    eligible: list[int],
) -> dict[str, tuple[dict[int, str], set[int]]]:
    """Partition an eligible index set into height bands, using each sample's crop_height."""
    bands: dict[str, tuple[dict[int, str], set[int]]] = {}
    for index in eligible:
        band = height_band_label(samples[index]["crop_height"])
        band_readable, band_unreadable = bands.setdefault(band, ({}, set()))
        if index in readable:
            band_readable[index] = readable[index]
        if index in unreadable:
            band_unreadable.add(index)
    return bands


def compatible_resume(report: dict, dataset_path: Path, model: str) -> bool:
    return (
        report.get("schema_version") == 1
        and report.get("dataset") == str(dataset_path)
        and report.get("model") == model
    )


def run_benchmark(args: argparse.Namespace) -> dict:
    dataset_path = args.dataset.resolve()
    labels_path = (args.labels or dataset_path.parent / "labels.json").resolve()
    output_path = (
        args.output or dataset_path.parent / "qwen38_flash_next_benchmark.json"
    ).resolve()
    dataset = json.loads(dataset_path.read_text())
    samples = {int(item["index"]): item for item in dataset["samples"]}
    readable, unreadable, unsure = load_ground_truth(labels_path)
    labelled = sorted(set(readable) | unreadable)
    missing = set(labelled) - set(samples)
    if missing:
        raise ValueError(f"labels reference samples absent from dataset: {sorted(missing)}")
    # Inference does not need labels -- only scoring does. Running every sample while
    # labelling is still in progress means the expensive pass is already done when the
    # labels land, instead of blocking on them. Scoring still uses labels alone.
    eligible = sorted(samples) if args.all_samples else labelled

    selected_variants = args.variant or list(VARIANTS)
    if output_path.is_file():
        existing = json.loads(output_path.read_text())
        if not compatible_resume(existing, dataset_path, args.model):
            raise ValueError(
                f"existing report is incompatible; choose another --output: {output_path}"
            )
        report = existing
    else:
        report = {
            "schema_version": 1,
            "model": args.model,
            "base_url": args.base_url,
            "dataset": str(dataset_path),
            "labels": str(labels_path),
            "created_at": utc_now(),
            "readable_labels": len(readable),
            "unreadable_labels": len(unreadable),
            "unsure_labels": unsure,
            "variant_config": VARIANTS,
            "variants": {},
            "raw": {},
        }

    started = time.monotonic()
    for variant_name in selected_variants:
        variant = VARIANTS[variant_name]
        raw = report.setdefault("raw", {}).setdefault(variant_name, {})
        pending = [index for index in eligible if str(index) not in raw]
        for position, index in enumerate(pending, start=1):
            sample = samples[index]
            image_path = dataset_path.parent / sample[variant["path_key"]]
            request_started = time.monotonic()
            last_error = None
            for attempt in range(1, args.retries + 2):
                try:
                    content, usage = request_prediction(
                        args.base_url,
                        args.model,
                        image_path,
                        variant["prompt"],
                        args.timeout,
                        args.max_tokens,
                        variant.get("extra_body"),
                    )
                    prediction, parse_status = parse_for_variant(variant, content)
                    # A reasoning model that runs out of budget mid-thought returns
                    # empty content, which every parser reads as "no answer" and
                    # scoring reads as an abstention. That would let a token-budget
                    # misconfiguration masquerade as the model correctly declining --
                    # corrupting the one metric this benchmark exists to measure. Mark
                    # it distinctly so it can never be silently counted as evidence.
                    if not content.strip() and usage.get("completion_tokens", 0) >= args.max_tokens:
                        parse_status = "truncated"
                        # Reasoning length is not deterministic here: a crop that
                        # overruns the budget on one call routinely finishes in well
                        # under it on the next (sample 25 truncated at 1024, then
                        # answered in 96 tokens). So a truncation is a transient
                        # failure, not a verdict -- retry it like a network error
                        # rather than recording an empty answer.
                        if attempt <= args.retries:
                            last_error = "truncated"
                            continue
                    raw[str(index)] = {
                        "prediction": prediction,
                        "parse_status": parse_status,
                        "response": content,
                        "usage": usage,
                        "elapsed_seconds": time.monotonic() - request_started,
                    }
                    write_json_atomic(output_path, report)
                    print(
                        f"{variant_name} {position}/{len(pending)} "
                        f"sample={index} prediction={prediction or '<abstain>'} "
                        f"parse={parse_status}",
                        flush=True,
                    )
                    break
                except (RuntimeError, TimeoutError) as error:
                    last_error = error
                    if attempt > args.retries:
                        raise
                    time.sleep(min(2**attempt, 10))
            if last_error is not None and str(index) not in raw:
                raise last_error

        metrics = summarize_variant(readable, unreadable, raw)
        if args.stratify_by_height:
            bands = stratify_by_height(readable, unreadable, samples, eligible)
            metrics["height_bands"] = {
                band: summarize_variant(band_readable, band_unreadable, raw)
                for band, (band_readable, band_unreadable) in sorted(
                    bands.items(), key=lambda item: HEIGHT_BAND_ORDER[item[0]]
                )
            }
        report.setdefault("variants", {})[variant_name] = metrics
        write_json_atomic(output_path, report)

    report["last_run_elapsed_seconds"] = time.monotonic() - started
    report["updated_at"] = utc_now()
    write_json_atomic(output_path, report)
    return report


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dataset", type=Path, default=DEFAULT_DATASET)
    parser.add_argument("--labels", type=Path)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--base-url", default=DEFAULT_BASE_URL)
    parser.add_argument("--model", default=DEFAULT_MODEL)
    parser.add_argument("--variant", action="append", choices=sorted(VARIANTS))
    parser.add_argument(
        "--all-samples",
        action="store_true",
        help="run inference on every sample in the dataset, not just labelled ones, "
        "so the pass can proceed while labelling is still in progress",
    )
    parser.add_argument(
        "--stratify-by-height", action="store_true",
        help="also report metrics per crop-height band (see build_jersey_audit_set.py)",
    )
    parser.add_argument("--timeout", type=float, default=120)
    # Qwen3.8-Flash-Next is a reasoning model: it emits `reasoning_content` before
    # `content`, so a budget that only fits the answer is consumed entirely by the
    # reasoning and the answer comes back empty. Measured on this server: median 97
    # completion tokens, but hard crops reason far longer -- at a 320 cap, 10% of
    # requests truncated to an empty answer, and one of those returned a correct
    # "NONE" in 204 tokens when given room. Generation stops at the answer, so
    # headroom costs nothing on the requests that finish early.
    parser.add_argument("--max-tokens", type=int, default=1024)
    parser.add_argument("--retries", type=int, default=2)
    return parser.parse_args()


def main() -> None:
    report = run_benchmark(parse_args())
    print(json.dumps(report["variants"], indent=2))


if __name__ == "__main__":
    main()
